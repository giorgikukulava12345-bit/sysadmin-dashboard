import {readFileSync,writeFileSync} from 'node:fs';
import {VERIFIED_ROUTER_PORTS} from '../data/cisco-router-interface-seed.js';
import {PACKET_TRACER_MODELS,PACKET_TRACER_PROFILES,PACKET_TRACER_PORTS} from '../data/packet-tracer-routers.js';
const root=new URL('../',import.meta.url);
const data=JSON.parse(readFileSync(new URL('data/cisco-router-catalog-source.json',root),'utf8'));
data.models.push(...PACKET_TRACER_MODELS);
Object.assign(data.profiles,PACKET_TRACER_PROFILES);
Object.assign(VERIFIED_ROUTER_PORTS,PACKET_TRACER_PORTS);
const keys=['model','series','form_factor','wan_ports','lan_ports','expansion_slots','console_usb','features'].sort();
const models=new Set();
for(const row of data.models){
  if(models.has(row.model))throw Error('Duplicate model: '+row.model);models.add(row.model);
  if(JSON.stringify(Object.keys(row).sort())!==JSON.stringify(keys))throw Error('Invalid schema: '+row.model);
  const profile=data.profiles[row.model];
  if(!profile||!/^https:\/\/(?:www\.)?(?:cisco\.com|documentation\.meraki\.com|tutorials\.ptnetacad\.net)\//.test(profile.source_url||''))throw Error('Missing official source: '+row.model);
}
const ge=(count,prefix='GigabitEthernet0/0/',type='RJ-45',start=0)=>Array.from({length:count},(_,i)=>({value:prefix+(start+i),type,speed:'1 Gbps',switched:false}));
for(const row of data.models){
  const name=row.model,p=data.profiles[name];
  if(/^Cisco C(?:1111X?|1121X?|1161X?|1101)-/.test(name)&&!VERIFIED_ROUTER_PORTS[name]){
    const ethernet=(p.groups||[]).filter(g=>g.role==='wan'&&g.speed==='1 Gbps'),count=ethernet.reduce((n,g)=>n+g.count,0);
    const lan=(p.groups||[]).find(g=>g.role==='lan');
    if(count&&count<=2&&lan){
      VERIFIED_ROUTER_PORTS[name]={wan:ethernet.flatMap(g=>Array.from({length:g.count},(_,i)=>({...ge(1)[0],value:'GigabitEthernet0/0/'+(g.type.includes('combo')?0:count===1?0:1),type:g.type}))),lan:ge(lan.count,'GigabitEthernet0/1/').map(port=>({...port,switched:true}))};
      p.cli_supported=true;
      p.port_note='Ethernet onboard CLI mapping. Cellular and DSL inventory is shown in specifications; their CLI bindings require the hardware guide.';
    }
  }
  if(name.startsWith('Cisco C8300-')&&!VERIFIED_ROUTER_PORTS[name]){
    const ten=name.endsWith('4T2X'),base=VERIFIED_ROUTER_PORTS['Cisco C8300-2N2S-4T2X'].wan.map(port=>({...port,...(!ten&&port.value.startsWith('Ten')?{value:port.value.replace('TenGigabitEthernet','GigabitEthernet'),speed:'1 Gbps',type:'SFP'}:{})}));
    VERIFIED_ROUTER_PORTS[name]={wan:base,lan:base};p.cli_supported=true;p.port_note='Onboard routed interfaces; expansion modules are separate.';
  }
  if(name==='Cisco C8200L-1N-4T'){VERIFIED_ROUTER_PORTS[name]=VERIFIED_ROUTER_PORTS['Cisco C8200-1N-4T'];p.cli_supported=true;}
}
const json=JSON.stringify(data.models,null,2)+'\n';
writeFileSync(new URL('static/vpn/cisco-routers.json',root),json);
const generated='// Generated by scripts/build-router-catalog.mjs. Edit the reviewed source data.\n'+
  'export const CATALOG_CHECKED_AT='+JSON.stringify(data.checked_at)+';\n'+
  'export const CATALOG_LISTING='+JSON.stringify(data.listing)+';\n'+
  'export const ROUTER_CATALOG='+JSON.stringify(data.models)+';\n'+
  'export const ROUTER_PROFILES='+JSON.stringify(data.profiles)+';\n'+
  'export const VERIFIED_ROUTER_PORTS='+JSON.stringify(VERIFIED_ROUTER_PORTS)+';\n';
writeFileSync(new URL('static/vpn/cisco-router-catalog.js',root),generated);
console.log(models.size+' official-source router models; '+Object.values(data.profiles).filter(p=>p.cli_supported).length+' verified CLI mappings.');
