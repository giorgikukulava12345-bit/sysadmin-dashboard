import assert from 'node:assert/strict';
import {terminalText,displayTerminalText} from '../static/vpn/cli-export.js';

const source='\uFEFFconfigure terminal\r\nhostname R1\rip dhcp pool USERS\n network 192.168.1.0 255.255.255.0\n exit\nusername operator secret ExampleOnly_2026\nend';
const result=terminalText(source,{vendor:'ios'});
assert.ok(result.startsWith('!\r\nconfigure terminal\r\n'));
assert.ok(result.endsWith('end\r\n'));
assert.equal(result.replaceAll('\r\n','').includes('\n'),false,'No bare LF remains in the IOS payload');
assert.equal(result.replaceAll('\r\n','').includes('\r'),false,'No bare CR remains in the IOS payload');
assert.equal(result.replaceAll('\r\n','\n').slice(2),source.slice(1).replace(/\r\n?/g,'\n')+'\n','Commands, indentation and real secrets retain their order');
assert.equal(terminalText(result,{vendor:'ios'}),result,'Formatting a prepared payload is idempotent');
assert.equal(displayTerminalText(source,{vendor:'ios'}),result.replaceAll('\r\n','\n'));
const blocks='! BASE\nconfigure terminal\ninterface Gi0/0\n no shutdown\n exit\nend\n! NEXT\nconfigure terminal\nip route 0.0.0.0 0.0.0.0 203.0.113.9\nend\n';
assert.equal(terminalText(blocks,{vendor:'ios'}).split('configure terminal').length,3,'Configuration mode boundaries are never collapsed');
assert.equal(terminalText(blocks,{vendor:'ios'}).split('\n').filter(x=>x.trim()==='end').length,2);
for(const vendor of ['mikrotik','juniper','fortinet','paloalto','asa'])assert.equal(terminalText('native command\n',{vendor}),'native command\n','No IOS preamble for '+vendor);
assert.equal(terminalText('sudo ip link set eth0 up',{vendor:'ios',role:'host'}),'sudo ip link set eth0 up\n');
assert.equal(terminalText('',{vendor:'ios'}),'');
assert.doesNotMatch(result,/\x1b|\x15|\x1a|write memory|copy running-config/,'No hidden terminal keys or unsolicited save commands');
const screenshotCommands='configure terminal\nservice timestamps log datetime msec localtime show-timezone\nntp server 129.250.35.251 prefer\nip name-server 8.8.8.8 1.1.1.1\nip dhcp pool USERS\n dns-server 8.8.8.8 1.1.1.1\n lease 7\n exit\ninterface GigabitEthernet0/0\n description WAN_TO_ISP\nend';
const ptContext={vendor:'ios',model:'Cisco 1941 (Packet Tracer)'};
const fragments='configure terminal\ninterface GigabitEthernet0/0\n ip nat outside\n ip virtual-reassembly in\n no shutdown\n exit\ninterface GigabitEthernet0/1\n ip nat inside\n ip virtual-reassembly in\n no shutdown\n exit\nend';
const fragmentExport=terminalText(fragments,ptContext);
assert(!fragmentExport.includes('ip virtual-reassembly'));
assert(fragmentExport.includes('ip nat inside'));assert(fragmentExport.includes('ip nat outside'));
assert.equal(fragmentExport.split('no shutdown').length,3);
assert.equal(displayTerminalText(fragments,ptContext),fragmentExport.replaceAll('\r\n','\n'));
assert(terminalText(fragments,{vendor:'ios',model:'Cisco ISR 4331'}).includes('ip virtual-reassembly in'));
const pt=terminalText(screenshotCommands,ptContext);
assert(pt.includes('service timestamps log datetime msec\r\n'));
assert(pt.includes('ntp server 129.250.35.251\r\n'));
assert(pt.includes('ip name-server 8.8.8.8\r\n'));assert(!pt.includes('ip name-server 1.1.1.1'));assert.equal((pt.match(/^ip name-server /gm)||[]).length,1);
assert(pt.includes(' dns-server 8.8.8.8\r\n'));assert(!pt.includes('dns-server 8.8.8.8 1.1.1.1'));
assert(!/^\s*lease 7/m.test(pt));assert(pt.includes('simulator default applies'));
assert(pt.includes('interface GigabitEthernet0/0\r\n description WAN_TO_ISP\r\nend\r\n'));
assert.equal(terminalText(pt,ptContext),pt);
assert.equal(displayTerminalText(screenshotCommands,ptContext),pt.replaceAll('\r\n','\n'));
const hardware=terminalText(screenshotCommands,{vendor:'ios',model:'Cisco ISR 4331'});
assert(hardware.includes('show-timezone'));assert(hardware.includes('lease 7'));
assert(terminalText(screenshotCommands,{vendor:'juniper',model:ptContext.model}).includes(' prefer'));
console.log('CLI export: transport, mode boundaries, vendor isolation and screenshot Packet Tracer syntax regressions passed.');

