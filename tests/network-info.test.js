import assert from 'node:assert/strict';
import {loadNetworkInfo,normalizeNetworkInfo,validPublicIp,renderNetworkInfo} from '../static/vpn/network-info.js';
const primary={ip:'203.0.113.9',country_code:'GE',city:'Tbilisi',org:'AS123 Example ISP'};
assert.deepEqual(normalizeNetworkInfo(primary,'test'),{ip:primary.ip,country:'Georgia',countryCode:'GE',city:'Tbilisi',isp:'Example ISP',provider:'test'});
assert.equal(normalizeNetworkInfo({...primary,country_code:'ZZ'},'test').country,'');
assert.equal(normalizeNetworkInfo({error:true},'test'),null);
assert.equal(validPublicIp('invalid'), '');
assert.equal(validPublicIp('2001:db8::1'),'2001:db8::1');
const mock=(responses,calls=[])=>async(url,options)=>{calls.push(url);assert.equal(options.credentials,'omit');const next=responses.shift();if(next instanceof Error)throw next;return {ok:next!==429,json:async()=>next};};
let calls=[];
let result=await loadNetworkInfo({fetchImpl:mock([primary],calls)});
assert.equal(calls.length,1);assert.equal(calls[0],'https://ipapi.co/json/');assert.equal(result.country,'Georgia');assert.equal(result.city,'Tbilisi');
result=await loadNetworkInfo({fetchImpl:mock([429,{ip:primary.ip,country:'Georgia',connection:{isp:'Fallback ISP'}}])});
assert.equal(result.isp,'Fallback ISP');assert.equal(result.country,'Georgia');
calls=[];
result=await loadNetworkInfo({fetchImpl:mock([{ip:primary.ip},{ip:primary.ip,country_code:'GE',org:'Other ISP'}],calls)});
assert.equal(result.country,'Georgia');assert(calls[1].includes(primary.ip));
result=await loadNetworkInfo({fetchImpl:mock([{ip:primary.ip},{...primary,ip:'198.51.100.1'}])});
assert.equal(result.country,'');assert.equal(result.isp,'');
result=await loadNetworkInfo({fetchImpl:mock([new Error('bad JSON'),{success:false},{ip:primary.ip}])});
assert.equal(result.ip,primary.ip);assert.equal(result.country,'');
result=await loadNetworkInfo({fetchImpl:mock([new Error(),new Error(),new Error()])});
assert.equal(result.ip,'');
result=await loadNetworkInfo({fetchImpl:()=>new Promise(()=>{}),timeoutMs:2});
assert.equal(result.country,'');
const nodes=Object.fromEntries(['geo-ip-display','geo-isp','geo-location','geo-flag'].map(id=>['#'+id,{}]));
renderNetworkInfo({querySelector:id=>nodes[id]},result);
assert.equal(nodes['#geo-location'].textContent,'Location unavailable');
renderNetworkInfo({querySelector:id=>nodes[id]},normalizeNetworkInfo(primary,'test'));
assert.equal(nodes['#geo-location'].textContent,'Tbilisi, Georgia');assert(nodes['#geo-location'].title.includes('IP-based'));assert.equal(nodes['#geo-flag'].hidden,false);
for(const city of ['',null,'Unknown','N/A','<script>','null'])assert.equal(normalizeNetworkInfo({...primary,city},'test').city,'');
renderNetworkInfo({querySelector:id=>nodes[id]},normalizeNetworkInfo({...primary,city:null},'test'));assert.equal(nodes['#geo-location'].textContent,'Georgia');
renderNetworkInfo({querySelector:id=>nodes[id]},{country:'Germany',countryCode:'DE',city:'Berlin'});assert.equal(nodes['#geo-flag'].hidden,true);
result=await loadNetworkInfo({fetchImpl:mock([{...primary,city:''},{...primary,city:'Tbilisi'}])});assert.equal(result.city,'Tbilisi');
result=await loadNetworkInfo({fetchImpl:mock([{...primary,city:''},{...primary,country_code:'DE',city:'Berlin'}])});assert.equal(result.city,'');
renderNetworkInfo(null,result);
console.log('GeoIP tests passed: primary, fallback, partial data, IP consistency, outage, timeout and city extraction, country fallback and conditional flag rendering.');
